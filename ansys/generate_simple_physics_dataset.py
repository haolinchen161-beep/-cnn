"""
First-layer simplified physics validation dataset generator.

This is a NEW standalone entrypoint. It does not replace generate_3d_test.py.

Purpose:
    Verify whether the MeshGraphNet branch can learn the basic mapping:
        simplified geometry variation -> modal omega/zeta/phi -> FRF.

Simplifications compared with ansys/generate_3d_test.py:
    1. Fixed material: E = E_BASE, rho = RHO_BASE.
    2. Fixed pocket grid jitter: GRID_JITTER = 0.
    3. Fixed pocket layout scheme by default: 5-pocket scheme.
    4. Fixed boundary condition: four corner spring areas only.
    5. Fixed spring stiffness/damping ranges: constants instead of random ranges.
    6. Optional mode-3 Z-dominant filter via REQUIRE_MODE3_Z=1.

Generated files:
    ansys/data_simple_physics/train.h5
    ansys/data_simple_physics/val.h5
    ansys/data_simple_physics/test.h5

Default sample split is intentionally smaller for quick validation:
    SIMPLE_N_SAMPLES=180, SIMPLE_N_TRAIN=144, SIMPLE_N_VAL=18, SIMPLE_N_TEST=18

You can override these through environment variables, for example:
    set SIMPLE_N_SAMPLES=300
    set SIMPLE_N_TRAIN=240
    set SIMPLE_N_VAL=30
    set SIMPLE_N_TEST=30
    set SIMPLE_LAYOUT_SCHEME=5
    set REQUIRE_MODE3_Z=0
    F:/pytorch_cuda12/python.exe -B ansys/generate_simple_physics_dataset.py
"""
from __future__ import annotations

import os
from pathlib import Path


ROOT = Path(__file__).resolve().parent
BASE_GENERATOR = ROOT / "generate_3d_test.py"


def _env_default(src_name: str, dst_name: str, default: str) -> None:
    """Populate the original generator env variable from a simple-channel env variable."""
    os.environ[src_name] = os.getenv(dst_name, os.getenv(src_name, default))


def _patch_source(source: str) -> str:
    """Patch the existing generator source for the simplified channel."""
    replacements = {
        'N_SAMPLES = int(os.getenv("N_SAMPLES", "300"))':
            'N_SAMPLES = int(os.getenv("N_SAMPLES", "180"))',
        'N_TRAIN = int(os.getenv("N_TRAIN", "240"))':
            'N_TRAIN = int(os.getenv("N_TRAIN", "144"))',
        'N_VAL = int(os.getenv("N_VAL", "30"))':
            'N_VAL = int(os.getenv("N_VAL", "18"))',
        'N_TEST = int(os.getenv("N_TEST", "30"))':
            'N_TEST = int(os.getenv("N_TEST", "18"))',
        'GRID_JITTER = 0.15':
            'GRID_JITTER = 0.0  # simple_physics: fixed pocket grid division',
        'K_CORNER_RANGE = (5e6, 1e8)':
            'K_CORNER_RANGE = (5e7, 5e7)  # simple_physics: fixed corner stiffness',
        'K_SIDE_RANGE = (1e6, 3e7)':
            'K_SIDE_RANGE = (1e7, 1e7)  # simple_physics: unused when side supports are disabled',
        'ZETA_JOINT_RANGE = (0.005, 0.05)':
            'ZETA_JOINT_RANGE = (0.02, 0.02)  # simple_physics: fixed joint damping ratio',
        'OUT_DIR = os.path.join(os.path.dirname(__file__), "data")':
            'OUT_DIR = os.path.join(os.path.dirname(__file__), "data_simple_physics")',
        'VIZ_DIR = os.path.join(os.path.dirname(__file__), "mesh_viz")':
            'VIZ_DIR = os.path.join(os.path.dirname(__file__), "mesh_viz_simple_physics")',
        'scaled_sobol = qmc.scale(sobol_samples, [E_RANGE[0], RHO_RANGE[0]], [E_RANGE[1], RHO_RANGE[1]])':
            'scaled_sobol = np.ones((N_SAMPLES + SOBOL_BUFFER, 2), dtype=np.float64)  # simple_physics: fixed E/rho',
        'num_machined = random.choice([5, 6, 7])':
            'num_machined = int(os.getenv("SIMPLE_LAYOUT_SCHEME", "5"))  # simple_physics: fixed pocket layout scheme',
        'side_choices = [0, 0, 1] if random.random() < 0.5 else [1, 1, 0]':
            'side_choices = []  # simple_physics: disable random side supports; keep four corner springs only',
        'print(f"激励点: 随机已加工凹槽的底面中心附近节点，排除凹槽边缘")':
            'print(f"激励点: 随机已加工凹槽的底面中心附近节点，排除凹槽边缘")\n'
            'print("简化通道: fixed E/rho, fixed grid, fixed boundary=four corner springs, fixed spring K/C")',
        'f.attrs["description"] = "MeshGraphNet dataset generated by mass-normalized modal analysis."':
            'f.attrs["description"] = "Simple-physics MeshGraphNet dataset: fixed material and boundary; geometry variation only."',
    }
    for old, new in replacements.items():
        if old not in source:
            raise RuntimeError(f"Patch anchor not found in generate_3d_test.py: {old}")
        source = source.replace(old, new)

    z_filter_anchor = '        modal_stiffness = (omega_k ** 2 * modal_mass).astype(np.float32)\n\n        # ---------- 8. 激励点 ----------'
    z_filter_code = '''        modal_stiffness = (omega_k ** 2 * modal_mass).astype(np.float32)

        # Optional simplified-channel filter: keep only mode-3 Z-dominant samples.
        mode_energy = np.sum(phi_xyz ** 2, axis=0)  # [K, 3]
        mode_ratio = mode_energy / (np.sum(mode_energy, axis=-1, keepdims=True) + 1e-12)
        mode_dir = np.argmax(mode_ratio, axis=-1)  # 0:X, 1:Y, 2:Z
        if os.getenv("REQUIRE_MODE3_Z", "0") == "1" and int(mode_dir[2]) != 2:
            print(f"  跳过: mode3_dir={int(mode_dir[2])} 非Z主导, ratio={mode_ratio[2]}")
            continue

        # ---------- 8. 激励点 ----------'''
    if z_filter_anchor not in source:
        raise RuntimeError("Patch anchor for optional mode-3 Z filter not found.")
    source = source.replace(z_filter_anchor, z_filter_code)

    return source


def main() -> int:
    if not BASE_GENERATOR.exists():
        raise FileNotFoundError(BASE_GENERATOR)

    # Map simple-channel environment names to the original generator names.
    _env_default("N_SAMPLES", "SIMPLE_N_SAMPLES", "180")
    _env_default("N_TRAIN", "SIMPLE_N_TRAIN", "144")
    _env_default("N_VAL", "SIMPLE_N_VAL", "18")
    _env_default("N_TEST", "SIMPLE_N_TEST", "18")
    _env_default("DATASET_SEED", "SIMPLE_DATASET_SEED", "11")

    source = BASE_GENERATOR.read_text(encoding="utf-8")
    patched = _patch_source(source)

    # Execute the patched generator as a standalone script while keeping __file__
    # pointed at this file so OUT_DIR/VIZ_DIR resolve to ansys/data_simple_physics.
    globals_dict = {
        "__name__": "__main__",
        "__file__": str(Path(__file__).resolve()),
        "__package__": None,
    }
    exec(compile(patched, str(BASE_GENERATOR), "exec"), globals_dict)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
